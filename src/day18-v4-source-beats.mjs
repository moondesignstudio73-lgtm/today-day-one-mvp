export function day18V4DirectedDialogue(number,from,to) {
  return day18V4SourceDialogue(number,from,to).flatMap(step=>[
    ...(before.get(`${number}|${step.text}`)??[]),step,...(after.get(`${number}|${step.text}`)??[])
  ]);
}

export function validateDay18V4BeatAnchors() {
  for(const key of [...before.keys(),...after.keys()]) {
    const split=key.indexOf('|'),number=Number(key.slice(0,split)),text=key.slice(split+1);
    if(!DAY18_V4_SOURCE_SCENES[number-1]?.body.includes(`“${text}”`))throw new Error(`DAY18_BEAT_ANCHOR_MISSING:${key}`);
  }
  return true;
}
