function routeRecall(day,state){
  const history=Array.isArray(state?.storyHistory)?state.storyHistory:[];
  const has=target=>history.some(entry=>entry?.sceneId===target);
  if(day===20&&has("m30-day19-current-shared-chore"))return [m("어제 접어 둔 큰 계획 대신 오늘의 작은 약속을 먼저 꺼냈다.")];
  if(day===23&&has("m30-day22-current-recovery-day"))return [m("어제 함께 고친 여행은 돌아가는 시간까지 남아 있었다.")];
  if(day===28&&has("m30-day27-current-final-check"))return [m("어제 들은 대답을 없던 일로 만들지 않은 채 약속 장소로 향했다.")];
  return [];
}

export function expandLateStoryV4(day,stage,state,baseSteps){
  const authored=CONTENT[day]?.[Math.min(3,Math.max(0,stage))]??[];
  const labels=SOURCE_CHOICE_LABELS[day]?.[Math.min(2,Math.max(0,stage))];
  let transitionIndex=0;
  const clean=baseSteps
    .filter(step=>["transition","characterEnter","choice","sceneEnd"].includes(step?.type))
    .map(step=>{
      if(step.type==="choice"&&labels)return {...step,options:step.options.map((option,index)=>({...option,label:labels[index]??option.label}))};
      if(step.type==="transition"&&!/END/.test(step.label??"")){
        transitionIndex+=1;
        return {...step,label:stage===0&&transitionIndex===1?"DAY "+day+" · "+SOURCE_TITLES[day]:"SCENE · "+SOURCE_TITLES[day]};
      }
      return step;
    });
  const endTransition=clean.findIndex(step=>step?.type==="transition"&&/END/.test(step.label??""));
  const insertAt=endTransition>=0?endTransition:clean.findIndex(step=>step?.type==="choice"||step?.type==="sceneEnd");
  const additions=[...routeRecall(day,state),...authored];
  if(insertAt<0)return [...clean,...additions];
  return [...clean.slice(0,insertAt),...additions,...clean.slice(insertAt)];
}

export function validateLateStoryV4(day){
  const stages=CONTENT[day];
  return Array.isArray(stages)&&stages.length===4&&stages.every(stage=>stage.filter(step=>step.type==="dialogue").length>=5)&&stages.flat().every(step=>step.type!=="narration");
}

export function recordLateStoryV4Choice(state,day,choiceId){
  state.storyFlags??={};
  if(day===20&&state.storyFlags.day20V4)return state.storyFlags.day20V4Choices??[];
  const key=`day${day}V4Choices`;
  const current=Array.isArray(state.storyFlags[key])?state.storyFlags[key]:[];
  if(!current.some(entry=>entry.choiceId===choiceId)){
    state.storyFlags[key]=[...current,{stage:state.storyFlags[`day${day}RuntimeStage`]??0,choiceId}];
  }
  return state.storyFlags[key];
}
